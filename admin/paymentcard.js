// ---------------------------------------------------------------------
// Logo upload helper for Admin Settings.
// Complete payment-card rendering and QR generation now live in the
// Google Apps Script Index.html service.
// ---------------------------------------------------------------------
async function loadImageFromDataUrl_(dataUrl) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => resolve(img);
    img.onerror = reject;
    img.src = dataUrl;
  });
}

/** Resize an uploaded logo before storing it in Apps Script settings. */
async function resizeLogoFile(file, maxSize) {
  maxSize = maxSize || 320;
  const dataUrl = await new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result);
    reader.onerror = reject;
    reader.readAsDataURL(file);
  });
  const img = await loadImageFromDataUrl_(dataUrl);
  const scale = Math.min(1, maxSize / Math.max(img.width, img.height));
  const w = Math.round(img.width * scale);
  const h = Math.round(img.height * scale);
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const ctx = canvas.getContext('2d');
  ctx.drawImage(img, 0, 0, w, h);
  return canvas.toDataURL('image/png');
}
