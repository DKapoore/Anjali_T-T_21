function atrGetLang() { return localStorage.getItem(ATR_LANG_KEY) || 'en'; }
function atrSetLang(lang) { localStorage.setItem(ATR_LANG_KEY, lang); }
function t(key) {
  const lang = atrGetLang();
  return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
}
function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-placeholder')); });
  document.querySelectorAll('.lang-pill').forEach(btn => { btn.classList.toggle('active', btn.dataset.lang === atrGetLang()); });
}
